// Builds data.js: the month-by-month piece schedule for both savers (1 piece = 20 million VND).
// Each month: the balance earns 10%/12, then 2 million is added (end-of-month contributions, the
// FV formula in FACTS.md). A piece is placed when the
// rounded count of contributed (wood) or interest (copper) pieces goes up, in that order.
// Usage: node tools/data.mjs <project>
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = path.resolve(process.argv[2] ?? '.');
const MONTHLY = 2e6, R = 0.10 / 12, UNIT = 20e6;

function saver(startAge, endAge = 55) {
  const pieces = [];
  let bal = 0, paid = 0, nWood = 0, nCopper = 0;
  for (let m = 1; m <= (endAge - startAge) * 12; m++) {
    bal = bal * (1 + R) + MONTHLY;             // the balance earns a month's interest, then the month's 2 million goes in
    paid += MONTHLY;
    const age = startAge + m / 12;
    const wood = Math.round(paid / UNIT), copper = Math.round((bal - paid) / UNIT);
    while (nWood < wood) pieces.push({ k: 'w', age: +age.toFixed(4) }), nWood++;
    while (nCopper < copper) pieces.push({ k: 'c', age: +age.toFixed(4) }), nCopper++;
  }
  return { startAge, paid, final: bal, wood: nWood, copper: nCopper, pieces };
}

const an = saver(25), binh = saver(35);
// The age at which An's interest pieces first outnumber the contributed ones.
let w = 0, c = 0, crossAge = null;
for (const p of an.pieces) { p.k === 'w' ? w++ : c++; if (crossAge === null && c > w) crossAge = p.age; }

const out = `// Generated by tools/data.mjs — do not edit. Example figures, not market data (FACTS.md).
export const UNIT = ${UNIT}, MONTHLY = ${MONTHLY}, ANNUAL = 0.10;
export const AN = ${JSON.stringify({ ...an, pieces: undefined })};
export const BINH = ${JSON.stringify({ ...binh, pieces: undefined })};
export const AN_PIECES = ${JSON.stringify(an.pieces)};
export const BINH_PIECES = ${JSON.stringify(binh.pieces)};
export const CROSS_AGE = ${crossAge};
`;
writeFileSync(path.join(dir, 'data.js'), out);
console.log(`An ${an.wood} wood + ${an.copper} copper = ${an.wood + an.copper} (${(an.final / 1e9).toFixed(3)} tỷ)`);
console.log(`Bình ${binh.wood} wood + ${binh.copper} copper = ${binh.wood + binh.copper} (${(binh.final / 1e9).toFixed(3)} tỷ)`);
console.log(`An's copper passes wood at age ${crossAge}`);
